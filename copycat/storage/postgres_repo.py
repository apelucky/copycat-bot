"""Postgres repository (Supabase-compatible).

Used when DATABASE_URL is set. The same methods as SqliteRepo, so a restart on Render's
ephemeral disk keeps traders, positions, balances, bench timers, cursors, and alert dedupe.

Supabase notes:
- Session pooler (port 5432) and transaction pooler (port 6543) both work.
- Prepared statements are disabled (`prepare_threshold=None`) because the transaction
  pooler rejects them.
- Remote hosts default to sslmode=require. A URL that already sets sslmode is left alone.
- Non-libpq query flags some ORMs add (`pgbouncer=true`) are stripped.
"""
from __future__ import annotations

import json
import logging
import threading
from typing import Any
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

import psycopg
from psycopg.conninfo import conninfo_to_dict, make_conninfo
from psycopg.errors import InterfaceError, OperationalError, UniqueViolation
from psycopg.rows import dict_row

log = logging.getLogger(__name__)

# Query keys ORMs tack on that libpq rejects.
_DROP_QUERY = {"pgbouncer", "supa", "connection_limit", "pool_timeout", "pgbouncer_mode"}

_SCHEMA = (
    """CREATE TABLE IF NOT EXISTS users(
        user_id BIGINT PRIMARY KEY,
        chat_id BIGINT,
        created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()))::bigint,
        settings TEXT)""",
    """CREATE TABLE IF NOT EXISTS accounts(
        user_id BIGINT, chain TEXT, balance DOUBLE PRECISION, start_balance DOUBLE PRECISION,
        PRIMARY KEY(user_id, chain))""",
    """CREATE TABLE IF NOT EXISTS positions(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT, chain TEXT, token TEXT, symbol TEXT, source TEXT, trader TEXT,
        tokens DOUBLE PRECISION, cost_native DOUBLE PRECISION, initial_tokens DOUBLE PRECISION,
        initial_cost DOUBLE PRECISION, realized DOUBLE PRECISION DEFAULT 0, fees DOUBLE PRECISION DEFAULT 0,
        opened_at BIGINT, closed_at BIGINT, status TEXT DEFAULT 'open', meta TEXT DEFAULT '{}')""",
    "CREATE INDEX IF NOT EXISTS ix_pos_user ON positions(user_id, chain, status)",
    """CREATE TABLE IF NOT EXISTS fills(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT, chain TEXT, position_id BIGINT, side TEXT, token TEXT, symbol TEXT,
        source TEXT, trader TEXT, tokens DOUBLE PRECISION, native DOUBLE PRECISION, price DOUBLE PRECISION,
        leader_price DOUBLE PRECISION, slippage_pct DOUBLE PRECISION, impact_pct DOUBLE PRECISION,
        fee_native DOUBLE PRECISION, gas_native DOUBLE PRECISION, pnl_native DOUBLE PRECISION,
        ts BIGINT, leader_sig TEXT, reason TEXT)""",
    "CREATE INDEX IF NOT EXISTS ix_fills_user ON fills(user_id, ts)",
    """CREATE TABLE IF NOT EXISTS skipped(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT, chain TEXT, token TEXT, symbol TEXT, trader TEXT, reason TEXT, ts BIGINT)""",
    """CREATE TABLE IF NOT EXISTS following(
        user_id BIGINT, chain TEXT, wallet TEXT, label TEXT, since BIGINT,
        PRIMARY KEY(user_id, chain))""",
    """CREATE TABLE IF NOT EXISTS trader_state(
        user_id BIGINT, chain TEXT, wallet TEXT, consec_losses INTEGER DEFAULT 0,
        benched_until BIGINT DEFAULT 0, bench_reason TEXT,
        PRIMARY KEY(user_id, chain, wallet))""",
    """CREATE TABLE IF NOT EXISTS leaderboard(
        chain TEXT, wallet TEXT, label TEXT, pnl DOUBLE PRECISION, wins INTEGER, losses INTEGER,
        trades INTEGER, score DOUBLE PRECISION, source TEXT, rank INTEGER, flagged TEXT, updated BIGINT,
        PRIMARY KEY(chain, wallet))""",
    """CREATE TABLE IF NOT EXISTS leader_events(
        chain TEXT, signature TEXT, wallet TEXT, token TEXT, side TEXT, ts BIGINT,
        token_amount DOUBLE PRECISION, native_amount DOUBLE PRECISION, symbol TEXT,
        PRIMARY KEY(chain, signature, wallet, token, side))""",
    "CREATE INDEX IF NOT EXISTS ix_le_ts ON leader_events(chain, ts)",
    """CREATE TABLE IF NOT EXISTS leader_holdings(
        chain TEXT, wallet TEXT, token TEXT, amount DOUBLE PRECISION,
        PRIMARY KEY(chain, wallet, token))""",
    """CREATE TABLE IF NOT EXISTS funders(
        chain TEXT, wallet TEXT, funder TEXT, checked_at BIGINT,
        PRIMARY KEY(chain, wallet))""",
    "CREATE TABLE IF NOT EXISTS kv(k TEXT PRIMARY KEY, v TEXT)",
)

_POS_COLS = {
    "user_id", "chain", "token", "symbol", "source", "trader", "tokens", "cost_native",
    "initial_tokens", "initial_cost", "realized", "fees", "opened_at", "closed_at", "status", "meta",
}
_FILL_COLS = {
    "user_id", "chain", "position_id", "side", "token", "symbol", "source", "trader", "tokens",
    "native", "price", "leader_price", "slippage_pct", "impact_pct", "fee_native", "gas_native",
    "pnl_native", "ts", "leader_sig", "reason",
}


def _is_local_host(host: str | None) -> bool:
    if not host:
        return True
    for part in host.split(","):
        h = part.strip().lower()
        if h.startswith("/"):
            continue
        if h not in {"", "localhost", "127.0.0.1", "::1"}:
            return False
    return True


def _strip_query(url: str) -> str:
    parts = urlsplit(url)
    if not parts.query:
        return url
    kept = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True) if k.lower() not in _DROP_QUERY]
    return urlunsplit((parts.scheme, parts.netloc, parts.path, urlencode(kept), parts.fragment))


def normalize_database_url(url: str) -> str:
    """Turn a Supabase (or other) URI into a libpq conninfo.

    Forces SSL on remote hosts unless the URL already chose an sslmode. Disables SCRAM
    channel binding, which the Supabase pooler does not offer. Does not log the password.
    """
    raw = url.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'":
        raw = raw[1:-1].strip()
    if raw.startswith("postgres://"):
        raw = "postgresql://" + raw[len("postgres://"):]
    if "://" in raw:
        raw = _strip_query(raw)
    info = conninfo_to_dict(raw)
    if not _is_local_host(str(info.get("host") or "")):
        info.setdefault("sslmode", "require")
        info.setdefault("channel_binding", "disable")
        info.setdefault("gssencmode", "disable")
    info.setdefault("connect_timeout", "15")
    info.setdefault("application_name", "copycat")
    info.setdefault("keepalives", "1")
    info.setdefault("keepalives_idle", "30")
    info.setdefault("keepalives_interval", "10")
    info.setdefault("keepalives_count", "3")
    return make_conninfo(**{k: v for k, v in info.items() if v is not None})


def safe_db_target(url: str) -> str:
    """Host and database only — never the password."""
    try:
        info = conninfo_to_dict(normalize_database_url(url))
    except Exception:  # noqa: BLE001
        return "postgres"
    host = info.get("host") or "localhost"
    port = info.get("port") or ""
    db = info.get("dbname") or ""
    return f"{host}:{port}/{db}" if port else f"{host}/{db}"


class PostgresRepo:
    def __init__(self, url: str):
        self.url = url.strip()
        self.conninfo = normalize_database_url(self.url)
        self.lock = threading.RLock()
        self.conn: psycopg.Connection | None = None
        self._connect()

    def _connect(self) -> None:
        if self.conn is not None and not self.conn.closed:
            try:
                self.conn.close()
            except Exception:  # noqa: BLE001
                pass
        self.conn = psycopg.connect(self.conninfo, autocommit=True, prepare_threshold=None, row_factory=dict_row)
        self.conn.prepare_threshold = None
        self._ensure_schema()

    def _ensure_schema(self) -> None:
        assert self.conn is not None
        for stmt in _SCHEMA:
            self.conn.execute(stmt)

    def close(self) -> None:
        with self.lock:
            if self.conn is not None and not self.conn.closed:
                self.conn.close()

    def _ensure(self) -> None:
        if self.conn is None or self.conn.closed:
            self._connect()

    def _exec(self, sql: str, args: tuple | list = ()) -> psycopg.Cursor:
        """Caller holds self.lock. Reconnects once if the pooler dropped us, then raises."""
        self._ensure()
        assert self.conn is not None
        try:
            return self.conn.execute(sql, args)
        except (OperationalError, InterfaceError):
            log.warning("postgres connection dropped; reconnecting")
            self._connect()
            raise

    def _q(self, sql: str, args: tuple | list = ()) -> list[dict[str, Any]]:
        with self.lock:
            return [dict(r) for r in self._exec(sql, args).fetchall()]

    def _one(self, sql: str, args: tuple | list = ()) -> dict[str, Any] | None:
        with self.lock:
            row = self._exec(sql, args).fetchone()
            return dict(row) if row else None

    def _x(self, sql: str, args: tuple | list = ()) -> None:
        with self.lock:
            self._exec(sql, args)

    @staticmethod
    def _check(allowed: set[str], cols: dict[str, Any]) -> None:
        bad = [k for k in cols if k not in allowed]
        if bad:
            raise ValueError(f"unknown column(s): {', '.join(bad)}")

    @staticmethod
    def _pos(r: dict[str, Any] | None) -> dict[str, Any] | None:
        if r is not None:
            r["meta"] = json.loads(r.get("meta") or "{}")
        return r

    def ping(self) -> bool:
        try:
            self._q("SELECT 1")
            return True
        except Exception:  # noqa: BLE001
            try:
                with self.lock:
                    self._connect()
                return True
            except Exception:  # noqa: BLE001
                log.warning("postgres ping failed", exc_info=True)
                return False

    # users
    def upsert_user(self, user_id: int, chat_id: int, default_settings: dict[str, Any]) -> bool:
        exists = self._q("SELECT 1 FROM users WHERE user_id=%s", (user_id,))
        if exists:
            self._x("UPDATE users SET chat_id=%s WHERE user_id=%s", (chat_id, user_id))
            return False
        self._x("INSERT INTO users(user_id, chat_id, settings) VALUES(%s,%s,%s)",
                (user_id, chat_id, json.dumps(default_settings)))
        return True

    def get_settings(self, user_id: int) -> dict[str, Any]:
        r = self._q("SELECT settings FROM users WHERE user_id=%s", (user_id,))
        return json.loads(r[0]["settings"]) if r and r[0]["settings"] else {}

    def save_settings(self, user_id: int, settings: dict[str, Any]) -> None:
        self._x("UPDATE users SET settings=%s WHERE user_id=%s", (json.dumps(settings), user_id))

    def list_users(self) -> list[dict[str, Any]]:
        return self._q("SELECT user_id, chat_id FROM users")

    # accounts
    def ensure_account(self, user_id: int, chain: str, start: float) -> None:
        self._x(
            "INSERT INTO accounts(user_id, chain, balance, start_balance) VALUES(%s,%s,%s,%s) "
            "ON CONFLICT (user_id, chain) DO NOTHING",
            (user_id, chain, start, start),
        )

    def get_account(self, user_id: int, chain: str) -> dict[str, Any] | None:
        r = self._q("SELECT * FROM accounts WHERE user_id=%s AND chain=%s", (user_id, chain))
        return r[0] if r else None

    def get_balance(self, user_id: int, chain: str) -> float:
        a = self.get_account(user_id, chain)
        return float(a["balance"]) if a else 0.0

    def add_balance(self, user_id: int, chain: str, delta: float) -> float:
        with self.lock:
            self._ensure()
            assert self.conn is not None
            with self.conn.transaction():
                self.conn.execute(
                    "UPDATE accounts SET balance=balance+%s WHERE user_id=%s AND chain=%s",
                    (delta, user_id, chain),
                )
                row = self.conn.execute(
                    "SELECT balance FROM accounts WHERE user_id=%s AND chain=%s",
                    (user_id, chain),
                ).fetchone()
            return float(row["balance"]) if row else 0.0

    # positions
    def open_position(self, **kw: Any) -> int:
        kw = dict(kw)
        kw["meta"] = json.dumps(kw.get("meta") or {})
        self._check(_POS_COLS, kw)
        cols = ",".join(kw)
        row = self._one(
            f"INSERT INTO positions({cols}) VALUES({','.join(['%s'] * len(kw))}) RETURNING id",
            list(kw.values()),
        )
        assert row is not None
        return int(row["id"])

    def get_position(self, pid: int) -> dict[str, Any] | None:
        return self._pos(self._one("SELECT * FROM positions WHERE id=%s", (pid,)))

    def find_open_position(self, user_id: int, chain: str, token: str, source: str | None = None) -> dict[str, Any] | None:
        sql = "SELECT * FROM positions WHERE user_id=%s AND chain=%s AND token=%s AND status='open'"
        args: list[Any] = [user_id, chain, token]
        if source:
            sql += " AND source=%s"
            args.append(source)
        return self._pos(self._one(sql + " ORDER BY id LIMIT 1", args))

    def open_positions(self, user_id: int | None = None, chain: str | None = None) -> list[dict[str, Any]]:
        sql, args = "SELECT * FROM positions WHERE status='open'", []
        if user_id is not None:
            sql += " AND user_id=%s"
            args.append(user_id)
        if chain:
            sql += " AND chain=%s"
            args.append(chain)
        return [self._pos(r) for r in self._q(sql + " ORDER BY id", args)]  # type: ignore[misc]

    def update_position(self, pid: int, **fields: Any) -> None:
        if not fields:
            return
        if "meta" in fields:
            fields["meta"] = json.dumps(fields["meta"])
        self._check(_POS_COLS, fields)
        sets = ",".join(f"{k}=%s" for k in fields)
        self._x(f"UPDATE positions SET {sets} WHERE id=%s", [*fields.values(), pid])

    def add_fill(self, **kw: Any) -> int:
        self._check(_FILL_COLS, kw)
        cols = ",".join(kw)
        row = self._one(
            f"INSERT INTO fills({cols}) VALUES({','.join(['%s'] * len(kw))}) RETURNING id",
            list(kw.values()),
        )
        assert row is not None
        return int(row["id"])

    def fills(self, user_id: int, since_ts: int = 0, chain: str | None = None) -> list[dict[str, Any]]:
        sql, args = "SELECT * FROM fills WHERE user_id=%s AND ts>=%s", [user_id, since_ts]
        if chain:
            sql += " AND chain=%s"
            args.append(chain)
        return self._q(sql + " ORDER BY ts, id", args)

    def closed_positions(self, user_id: int, since_ts: int = 0, chain: str | None = None, trader: str | None = None,
                         source: str | None = None, limit: int | None = None) -> list[dict[str, Any]]:
        sql, args = "SELECT * FROM positions WHERE user_id=%s AND status='closed' AND closed_at>=%s", [user_id, since_ts]
        for col, val in (("chain", chain), ("trader", trader), ("source", source)):
            if val:
                sql += f" AND {col}=%s"
                args.append(val)
        sql += " ORDER BY closed_at DESC, id DESC"
        if limit:
            sql += " LIMIT %s"
            args.append(int(limit))
        return [self._pos(r) for r in self._q(sql, args)]  # type: ignore[misc]

    def add_skip(self, user_id: int, chain: str, token: str, symbol: str | None, trader: str | None, reason: str, ts: int) -> None:
        self._x("INSERT INTO skipped(user_id, chain, token, symbol, trader, reason, ts) VALUES(%s,%s,%s,%s,%s,%s,%s)",
                (user_id, chain, token, symbol, trader, reason, ts))

    def skips(self, user_id: int, since_ts: int = 0) -> list[dict[str, Any]]:
        return self._q("SELECT * FROM skipped WHERE user_id=%s AND ts>=%s ORDER BY ts DESC, id DESC", (user_id, since_ts))

    # traders
    def get_following(self, user_id: int, chain: str) -> dict[str, Any] | None:
        r = self._q("SELECT * FROM following WHERE user_id=%s AND chain=%s", (user_id, chain))
        return r[0] if r and r[0]["wallet"] else None

    def set_following(self, user_id: int, chain: str, wallet: str | None, label: str | None, ts: int) -> None:
        self._x(
            "INSERT INTO following(user_id, chain, wallet, label, since) VALUES(%s,%s,%s,%s,%s) "
            "ON CONFLICT (user_id, chain) DO UPDATE SET wallet=EXCLUDED.wallet, label=EXCLUDED.label, since=EXCLUDED.since",
            (user_id, chain, wallet, label, ts),
        )

    def followers_of(self, chain: str, wallet: str) -> list[int]:
        return [r["user_id"] for r in self._q("SELECT user_id FROM following WHERE chain=%s AND wallet=%s", (chain, wallet))]

    def all_followed(self, chain: str) -> list[str]:
        return [r["wallet"] for r in self._q(
            "SELECT DISTINCT wallet FROM following WHERE chain=%s AND wallet IS NOT NULL", (chain,))]

    def trader_state(self, user_id: int, chain: str, wallet: str) -> dict[str, Any]:
        r = self._q("SELECT * FROM trader_state WHERE user_id=%s AND chain=%s AND wallet=%s", (user_id, chain, wallet))
        return r[0] if r else {"user_id": user_id, "chain": chain, "wallet": wallet, "consec_losses": 0, "benched_until": 0, "bench_reason": None}

    def save_trader_state(self, user_id: int, chain: str, wallet: str, **fields: Any) -> None:
        st = self.trader_state(user_id, chain, wallet)
        st.update(fields)
        self._x(
            "INSERT INTO trader_state(user_id, chain, wallet, consec_losses, benched_until, bench_reason) VALUES(%s,%s,%s,%s,%s,%s) "
            "ON CONFLICT (user_id, chain, wallet) DO UPDATE SET consec_losses=EXCLUDED.consec_losses, "
            "benched_until=EXCLUDED.benched_until, bench_reason=EXCLUDED.bench_reason",
            (user_id, chain, wallet, st["consec_losses"], st["benched_until"], st["bench_reason"]),
        )

    def benched(self, user_id: int, chain: str, now: int) -> list[dict[str, Any]]:
        return self._q("SELECT * FROM trader_state WHERE user_id=%s AND chain=%s AND benched_until>%s", (user_id, chain, now))

    def replace_leaderboard(self, chain: str, rows: list[dict[str, Any]], ts: int) -> None:
        with self.lock:
            self._ensure()
            assert self.conn is not None
            with self.conn.transaction():
                self.conn.execute("DELETE FROM leaderboard WHERE chain=%s", (chain,))
                for r in rows:
                    self.conn.execute(
                        "INSERT INTO leaderboard(chain, wallet, label, pnl, wins, losses, trades, score, source, rank, flagged, updated) "
                        "VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
                        (chain, r["wallet"], r["label"], r["pnl"], r["wins"], r["losses"], r["trades"], r["score"], r["source"],
                         r.get("rank"), r.get("flagged"), ts),
                    )

    def leaderboard(self, chain: str) -> list[dict[str, Any]]:
        return self._q("SELECT * FROM leaderboard WHERE chain=%s ORDER BY (flagged IS NOT NULL), rank", (chain,))

    # events
    def record_leader_event(self, ev: dict[str, Any]) -> bool:
        try:
            self._x(
                "INSERT INTO leader_events(chain, signature, wallet, token, side, ts, token_amount, native_amount, symbol) "
                "VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s)",
                (ev["chain"], ev["signature"], ev["wallet"], ev["token"], ev["side"], ev["timestamp"],
                 ev["token_amount"], ev["native_amount"], ev.get("symbol")),
            )
            return True
        except UniqueViolation:
            return False

    def leader_events(self, chain: str | None, since_ts: int, side: str | None = None) -> list[dict[str, Any]]:
        sql, args = "SELECT * FROM leader_events WHERE ts>=%s", [since_ts]
        if chain:
            sql += " AND chain=%s"
            args.append(chain)
        if side:
            sql += " AND side=%s"
            args.append(side)
        return self._q(sql + " ORDER BY ts", args)

    def leader_holding(self, chain: str, wallet: str, token: str) -> float:
        r = self._q("SELECT amount FROM leader_holdings WHERE chain=%s AND wallet=%s AND token=%s", (chain, wallet, token))
        return float(r[0]["amount"]) if r else 0.0

    def set_leader_holding(self, chain: str, wallet: str, token: str, amount: float) -> None:
        self._x(
            "INSERT INTO leader_holdings(chain, wallet, token, amount) VALUES(%s,%s,%s,%s) "
            "ON CONFLICT (chain, wallet, token) DO UPDATE SET amount=EXCLUDED.amount",
            (chain, wallet, token, max(0.0, amount)),
        )

    def holders_of(self, chain: str, token: str, wallets: list[str]) -> list[str]:
        if not wallets:
            return []
        return [r["wallet"] for r in self._q(
            "SELECT wallet FROM leader_holdings WHERE chain=%s AND token=%s AND amount>0 AND wallet = ANY(%s)",
            (chain, token, list(wallets)),
        )]

    def get_funder(self, chain: str, wallet: str) -> tuple[bool, str | None]:
        r = self._q("SELECT funder FROM funders WHERE chain=%s AND wallet=%s", (chain, wallet))
        return (True, r[0]["funder"]) if r else (False, None)

    def set_funder(self, chain: str, wallet: str, funder: str | None, ts: int) -> None:
        self._x(
            "INSERT INTO funders(chain, wallet, funder, checked_at) VALUES(%s,%s,%s,%s) "
            "ON CONFLICT (chain, wallet) DO UPDATE SET funder=EXCLUDED.funder, checked_at=EXCLUDED.checked_at",
            (chain, wallet, funder, ts),
        )

    # kv
    def kv_get(self, key: str, default: Any = None) -> Any:
        r = self._q("SELECT v FROM kv WHERE k=%s", (key,))
        return json.loads(r[0]["v"]) if r else default

    def kv_set(self, key: str, value: Any) -> None:
        self._x(
            "INSERT INTO kv(k, v) VALUES(%s,%s) ON CONFLICT (k) DO UPDATE SET v=EXCLUDED.v",
            (key, json.dumps(value)),
        )
